export type ReceiptOrder = {
  order_code?: string;
  weplay_id?: string;
  weplay_name?: string;
  product_name?: string;
  price?: number;
  coins_amount?: number | string | null;
  status?: string;
  transaction_id?: string | null;
  upi_id?: string | null;
  created_at?: string;
  failure_reason?: string | null;
  receipt_note?: string | null;
};

const esc = (v: unknown) =>
  String(v ?? "—").replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c] as string));

export function buildReceiptHtml(o: ReceiptOrder) {
  const status = (o.status || "pending").toUpperCase();
  const isFailed = (o.status || "").toLowerCase() === "failed";
  const note = o.failure_reason || o.receipt_note;

  const row = (label: string, value: unknown) =>
    `<tr><td class="l">${esc(label)}</td><td class="v">${esc(value)}</td></tr>`;

  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8" />
<title>Receipt ${esc(o.order_code)} · Lowest Weplay</title>
<meta name="viewport" content="width=device-width, initial-scale=1" />
<style>
  *{box-sizing:border-box}
  body{margin:0;font-family:ui-sans-serif,system-ui,-apple-system,"Segoe UI",Roboto,sans-serif;background:#f4f5fb;color:#111827;padding:24px}
  .card{max-width:640px;margin:0 auto;background:#fff;border:1px solid #e5e7eb;border-radius:20px;overflow:hidden}
  .head{padding:24px 28px;background:linear-gradient(135deg,#4338ca,#6366f1);color:#fff}
  .head h1{margin:0;font-size:20px;letter-spacing:.02em}
  .head p{margin:6px 0 0;font-size:12px;opacity:.85}
  .body{padding:24px 28px}
  table{width:100%;border-collapse:collapse;font-size:14px}
  td{padding:10px 0;border-bottom:1px dashed #e5e7eb;vertical-align:top}
  td.l{color:#6b7280;width:45%;font-size:12px;text-transform:uppercase;letter-spacing:.06em;font-weight:700}
  td.v{text-align:right;font-weight:600;word-break:break-all}
  .badge{display:inline-block;padding:4px 10px;border-radius:999px;font-size:11px;font-weight:800;letter-spacing:.08em;
    background:${isFailed ? "#fee2e2" : "#dcfce7"};color:${isFailed ? "#b91c1c" : "#15803d"}}
  .note{margin-top:18px;padding:14px 16px;border-radius:14px;font-size:13px;line-height:1.5;
    background:${isFailed ? "#fff1f2" : "#f5f3ff"};border:1px solid ${isFailed ? "#fecdd3" : "#ddd6fe"}}
  .note b{display:block;font-size:11px;text-transform:uppercase;letter-spacing:.08em;margin-bottom:4px;color:${isFailed ? "#b91c1c" : "#4338ca"}}
  .foot{padding:18px 28px;background:#f9fafb;font-size:11px;color:#6b7280;text-align:center;line-height:1.6}
  @media print{body{background:#fff;padding:0}.card{border:none}}
</style></head>
<body>
  <div class="card">
    <div class="head">
      <h1>Lowest Weplay · Payment Receipt</h1>
      <p>Official Lowest Weplay top-up service · independent reseller</p>
    </div>
    <div class="body">
      <table>
        ${row("Order ID", o.order_code)}
        ${row("Date", o.created_at ? new Date(o.created_at).toLocaleString() : "—")}
        ${row("Lowest WePlay ID", o.weplay_id)}
        ${row("Player Name", o.weplay_name)}
        ${row("Plan", o.product_name)}
        ${row("Coins", o.coins_amount)}
        ${row("Amount Paid", `INR ${o.price ?? "—"}`)}
        ${row("Paid To (UPI)", o.upi_id)}
        ${row("Transaction / UTR", o.transaction_id)}
        <tr><td class="l">Status</td><td class="v"><span class="badge">${esc(status)}</span></td></tr>
      </table>
      ${note ? `<div class="note"><b>${isFailed ? "Reason for failure" : "Note"}</b>${esc(note)}</div>` : ""}
    </div>
    <div class="foot">
      This receipt is generated by Lowest Weplay. Keep it for your records.<br />
      Support: use the Track Order page with your Lowest WePlay ID.
    </div>
  </div>
  <script>window.onload = function(){ setTimeout(function(){ window.print(); }, 300); };<\/script>
</body></html>`;
}

export function openReceipt(o: ReceiptOrder) {
  const html = buildReceiptHtml(o);
  const w = window.open("", "_blank");
  if (w) {
    w.document.write(html);
    w.document.close();
    return;
  }
  // Popup blocked → fall back to file download
  const blob = new Blob([html], { type: "text/html" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `receipt-${o.order_code || "order"}.html`;
  a.click();
  URL.revokeObjectURL(url);
}
